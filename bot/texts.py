MESSAGE_LIMIT = 4000

_overrides: dict[str, str] = {}
_extra: dict[str, list[str]] = {}


def set_overrides(texts: dict[str, str], extra: dict[str, list[str]] | None = None):
    _overrides.clear()
    _overrides.update({k: v for k, v in texts.items() if v.strip()})
    _extra.clear()
    _extra.update(extra or {})


def _escape_fit(text: str) -> str:
    """Экранирует текст и обрезает так, чтобы результат уложился в MESSAGE_LIMIT."""
    text = text[:MESSAGE_LIMIT]
    escaped = escape(text, quote=False)
    while len(escaped) > MESSAGE_LIMIT:
        text = text[:-(len(escaped) - MESSAGE_LIMIT)]
        escaped = escape(text, quote=False)
    return escaped


def extra(place: str) -> list[str]:
    """Добавленные в админке сообщения для указанного места (HTML-безопасные)."""
    return [_escape_fit(text) for text in _extra.get(place, [])]


def _render(key: str, values: dict) -> str:
    default = DEFAULT_TEXTS[key][1]
    template = _overrides.get(key, default)
    try:
        return template.format(**values)
    except (KeyError, IndexError, ValueError):
        return default.format(**values)


def t(key: str, **values) -> str:
    """Текст сообщения (HTML-безопасный)."""
    return escape(_render(key, values), quote=False)


def label(key: str, **values) -> str:
    """Надпись на кнопке (без HTML)."""
    return _render(key, values)
